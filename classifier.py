# Разделяем сообщения и категории автоматически.
texts = [text for text, label in examples]
labels = [label for text, label in examples]

# Проверяем качество на отдельной тестовой выборке.
X_train, X_test, y_train, y_test = train_test_split(
    texts,
    labels,
    test_size=0.2,
    random_state=42,
    stratify=labels,
)

def create_model():
    return Pipeline([
        ("tfidf", TfidfVectorizer(ngram_range=(1, 2))),
        ("classifier", MultinomialNB()),
    ])


# Отдельная модель для честной оценки качества.
evaluation_model = create_model()
evaluation_model.fit(X_train, y_train)
predictions = evaluation_model.predict(X_test)


# Рабочая модель обучается на всех примерах.
model = create_model()
model.fit(texts, labels)


def classify_text(text: str) -> str:
    return model.predict([text])[0]


